// 今日の1件を日付から決定的に選ぶ（同じ日は同じ内容、日が変わると次に切り替わる）。
function todaysKnowledgeEntry() {
  const now = new Date();
  const startOfYear = new Date(now.getFullYear(), 0, 0);
  const dayOfYear = Math.floor((now - startOfYear) / 86400000);
  return KNOWLEDGE_ENTRIES[dayOfYear % KNOWLEDGE_ENTRIES.length];
}

